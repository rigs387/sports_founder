import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { parse } from "yaml";

// Documentation fixture only. Regenerate from the game's content without a browser server.
const root = new URL("../../", import.meta.url);
const tree = parse(readFileSync(new URL("content/growth-tree.yaml", root), "utf8"));
const english = JSON.parse(
  readFileSync(new URL("src/renderer/src/i18n/locales/en.json", root), "utf8"),
);
const names = english.growth?.nodes ?? english.translation?.growth?.nodes;
if (!names) throw new Error("Cannot find localized growth node names");
const demo = parse(readFileSync(new URL("study.yaml", import.meta.url), "utf8"));
const data = {
  ...tree,
  demo,
  nodes: tree.nodes.map((node) => ({ ...node, name: names[node.id] })),
};
const output = new URL("data.js", import.meta.url);
writeFileSync(
  output,
  `// Generated by build-data.mjs; do not edit.\nwindow.GROWTH_STUDY = ${JSON.stringify(data, null, 2)};\n`,
);
console.log(`Wrote ${tree.nodes.length} nodes to ${fileURLToPath(output)}`);
